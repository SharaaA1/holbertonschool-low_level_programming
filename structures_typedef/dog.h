#ifndef DOG_H
#define DOG_H

/**
 * struct dog - a dog's basic info
 * @name: First member, name of the dog
 * @age: Second member, age of the dog
 * @owner: Third member, owner of the dog
 *
 * Description: Structure representing a dog with name, age, and owner.
 */
struct dog
{
	char *name;
	float age;
	char *owner;
};

#endif
